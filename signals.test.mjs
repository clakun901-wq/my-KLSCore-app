import assert from 'node:assert/strict';
import {createLocalSignals} from '../js/signals.js';
const {signal,computed,effect,batch}=createLocalSignals();
const a=signal(1),b=signal(2),sum=computed(()=>a.value+b.value);let runs=0,seen=[];
const stop=effect(()=>{runs++;seen.push(sum.value)});
assert.deepEqual(seen,[3]); a.value=5; assert.deepEqual(seen,[3,7]);
batch(()=>{a.value=10;b.value=20}); assert.deepEqual(seen,[3,7,30]);
a.value=10; assert.equal(runs,3,'nilai sama tidak memicu ulang');
const flag=signal(true),x=signal('x'),y=signal('y');let n=0;effect(()=>{n++;flag.value?x.value:y.value});
y.value='z';assert.equal(n,1,'dependensi cabang tidak aktif diabaikan');flag.value=false;assert.equal(n,2);y.value='q';assert.equal(n,3);x.value='w';assert.equal(n,3);
stop();a.value=99;assert.equal(runs,3,'effect dihentikan');
console.log('signals lokal OK');
