import assert from 'node:assert/strict';
import { createTheme } from '../js/theme.js';
const values = new Map([['kalsara_theme', 'dark'], ['kalsara_mode', 'full']]);
const attrs = new Map();
const themeButton = { setAttribute(k, v) { this[k] = v; } };
const modeButtons = [{ dataset: { m: 'fast' }, setAttribute(k, v) { this[k] = v; } }, { dataset: { m: 'full' }, setAttribute(k, v) { this[k] = v; } }];
const root = { setAttribute(k, v) { attrs.set(k, v); }, removeAttribute(k) { attrs.delete(k); }, getAttribute(k) { return attrs.get(k) || null; } };
const bodyClasses = new Set();
const document = { documentElement: root, body: { classList: { toggle(k, on) { on ? bodyClasses.add(k) : bodyClasses.delete(k); } } }, querySelectorAll() { return modeButtons; } };
const messages = [];
const KStore = { getItem(k) { return values.get(k) ?? null; }, setItem(k, v) { values.set(k, v); } };
const KDOM = { setHTML(el, html) { el.html = html; } };
const $ = id => id === 'thm' ? themeButton : { onclick: null };
const api = createTheme({ $, KStore, KDOM, toast: x => messages.push(x), document });
assert.equal(attrs.get('data-theme'), 'dark');
assert.equal(modeButtons[1]['aria-pressed'], true);
assert.equal(bodyClasses.has('fast'), false);
api.setTheme('light', true);
assert.equal(attrs.get('data-theme'), 'light');
assert.equal(values.get('kalsara_theme'), 'light');
api.setMode('fast', true);
assert.equal(bodyClasses.has('fast'), true);
assert.equal(values.get('kalsara_mode'), 'fast');
console.log('Theme module: 7 runtime assertions passed.');
